// Helper to shuffle questions for regular lesson runs
export function sampleQuestions(pool: Question[], count: number = 10): Question[] {
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, pool.length));
}

